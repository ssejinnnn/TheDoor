function getGridPosition(index) {

  const cols = 10;
  const rows = 5;

  const gridWidth =
    Math.min(
      window.innerWidth * 0.80,
      1260
    );

  const gridHeight =
    Math.min(
      window.innerHeight * 0.58,
      560
    );

  const col =
    index % cols;

  const row =
    Math.floor(
      index / cols
    );

  const stepX =
    gridWidth /
    (cols - 1);

  const stepY =
    gridHeight /
    (rows - 1);

  const startX =
    -gridWidth / 2;

  const startY =
    -gridHeight / 2 - 15;

  const x =
    startX +
    stepX * col;

  const y =
    startY +
    stepY * row;

  const width =
    Math.min(
      88,
      stepX * 0.60,
      stepY * 0.68
    );

  return {
    x,
    y,
    width
  };

}

function updateScrollState() {

  const storyStart =
    window.innerHeight * 0.55;

  const active =
    window.scrollY >
    storyStart;

  document.body.classList.toggle(
    "story-mode",
    active
  );

  if (
    !active
  ) {
    return;
  }

  hoveredItem = null;

  hideMetadata();

  items.forEach(item => {

    item.hovered =
      false;

    item.el.classList.remove(
      "is-hovered"
    );

  });

}

