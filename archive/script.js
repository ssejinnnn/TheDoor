function animate(time) {

  items.forEach(item => {

    const targetHover =
      item.hovered
        ? 1
        : 0;

    item.hoverAmount +=
      (
        targetHover -
        item.hoverAmount
      ) * 0.12;

    if (
      gridMode
    ) {

      const position =
        getGridPosition(
          item.index
        );

      item.el.style.width =
        `${position.width}px`;

      const scale =
        1 +
        item.hoverAmount *
        0.35;

      const hoverZ =
        item.hoverAmount *
        180;

      item.el.style.transform = `
        translate3d(
          ${position.x}px,
          ${position.y}px,
          ${hoverZ}px
        )
        scale(${scale})
      `;

      item.el.style.zIndex =
        item.hovered
          ? 9999
          : 100;

      let opacity = 1;

      if (
        hoveredItem &&
        hoveredItem !== item
      ) {

        opacity =
          0.25;

      }

      item.el.style.opacity =
        opacity;

      return;

    }

    item.el.style.width =
      `${item.floatWidth}px`;

    if (
      !item.hovered
    ) {

      item.z +=
        item.speed;

      item.x +=
        item.driftX;

      item.y +=
        item.driftY;

    }

    const depth =
      Math.max(
        0,
        Math.min(
          1,
          (
            item.z + 560
          ) / 830
        )
      );

    const waveX =
      Math.sin(
        time * 0.00016 +
        item.phase
      ) * 5;

    const waveY =
      Math.cos(
        time * 0.00013 +
        item.phase
      ) * 4;

    const parallaxX =
      mouseX *
      (
        7 +
        depth * 16
      );

    const parallaxY =
      mouseY *
      (
        5 +
        depth * 10
      );

    const hoverZ =
      item.hoverAmount *
      180;

    const scale =
      1 +
      item.hoverAmount *
      0.30;

    item.el.style.transform = `
      translate3d(
        ${
          item.x +
          waveX +
          parallaxX
        }px,

        ${
          item.y +
          waveY +
          parallaxY
        }px,

        ${
          item.z +
          hoverZ
        }px
      )

      scale(${scale})
    `;

    item.el.style.zIndex =
      item.hovered
        ? 9999
        : Math.round(
            100 +
            depth * 800
          );

    let opacity =
      0.48 +
      depth * 0.52;

    if (
      hoveredItem &&
      hoveredItem !== item
    ) {

      opacity *=
        0.55;

    }

    if (
      item.hovered
    ) {

      opacity =
        1;

    }

    item.el.style.opacity =
      opacity;

    if (
      item.z > 320 &&
      !item.hovered
    ) {

      item.z =
        -600 -
        Math.random() * 120;

      item.x =
        randomX();

      item.y =
        randomY();

      item.phase =
        Math.random() *
        Math.PI *
        2;

    }

  });

  requestAnimationFrame(
    animate
  );

}

